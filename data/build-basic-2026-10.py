def build(rows):
    out = []
    for i, (cat, q, ch, ex) in enumerate(rows):
        pos = i % 4                      # วนตำแหน่งคำตอบ 0 1 2 3
        correct, wrong = ch[0], ch[1:]
        choices = wrong[:pos] + [correct] + wrong[pos:]
        out.append({"cat": cat, "q": q, "ch": choices, "ans": pos, "ex": ex, "img": ""})
    return out


